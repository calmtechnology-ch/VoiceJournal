#!/usr/bin/env python3
"""
generate_parser_tables.py
Génère les tables constantes C++ (Flash / ROM) pour JournalParser
à partir des règles déclaratives JSON dans rules/
"""

import json
import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.dirname(script_dir)
    rules_dir = os.path.join(project_dir, "rules")
    output_header = os.path.join(project_dir, "include", "parser", "ParserTables.h")
    output_header_src = os.path.join(project_dir, "src", "parser", "ParserTables.h")

    with open(os.path.join(rules_dir, "concepts.json"), "r", encoding="utf-8") as f:
        concepts_data = json.load(f)["concepts"]

    with open(os.path.join(rules_dir, "entities.json"), "r", encoding="utf-8") as f:
        entities_data = json.load(f)["entities"]

    with open(os.path.join(rules_dir, "aliases.json"), "r", encoding="utf-8") as f:
        aliases_data = json.load(f)["aliases"]

    with open(os.path.join(rules_dir, "intents.json"), "r", encoding="utf-8") as f:
        intents_data = json.load(f)["intents"]

    with open(os.path.join(rules_dir, "phrases.json"), "r", encoding="utf-8") as f:
        phrases_data = json.load(f)["phrases"]

    with open(os.path.join(rules_dir, "grammar.json"), "r", encoding="utf-8") as f:
        grammar_data = json.load(f)["rules"]

    concept_names = list(concepts_data.keys())
    concept_to_bit = {c: i for i, c in enumerate(concept_names)}

    # Build lexicon word -> mask
    lexicon = {}
    for c, words in concepts_data.items():
        bit = concept_to_bit[c]
        for w in words:
            w_norm = w.strip().lower()
            if w_norm not in lexicon:
                lexicon[w_norm] = 0
            lexicon[w_norm] |= (1 << bit)

    sorted_words = sorted(lexicon.keys())

    # Build entity list (prefix with ENT_ to avoid ESP32 macro collision)
    entity_enums = ["ENT_NONE = 0"]
    for e in entities_data:
        entity_enums.append(f"ENT_{e['id']}")

    entity_types = sorted(list(set(e["type"] for e in entities_data)))
    entity_type_enums = ["NONE = 0"] + entity_types

    # Aliases
    entity_aliases = []
    for e in entities_data:
        for alias in e["aliases"]:
            entity_aliases.append((alias.strip().lower(), f"ENT_{e['id']}"))
    entity_aliases.sort(key=lambda x: x[0])

    # Exact confirm phrases
    confirm_phrases = []
    for item in intents_data:
        if item["id"] == "CONFIRM_CLEAR":
            for r in item.get("rules", []):
                for p in r.get("exact_phrases", []):
                    confirm_phrases.append(p.strip().lower())
    confirm_phrases.sort()

    semantic_roles = [
        "UNKNOWN",
        "SUBJECT",
        "ACTION",
        "OBJECT",
        "ENTITY",
        "QUANTIFIER",
        "QUALIFIER",
        "TIME",
        "NEGATION",
        "OBLIGATION",
        "QUESTION",
        "CONNECTOR",
        "PAYLOAD"
    ]

    target_categories = [
        "UNKNOWN_OBJECT",
        "JOURNAL",
        "JOURNAL_NOTE",
        "TASK",
        "PROJECT",
        "PROBLEM",
        "FILE",
        "DEVICE"
    ]

    # Sort phrases by token count desc, length desc, then alpha
    processed_phrases = []
    for p in phrases_data:
        phrase_str = p["phrase"].strip().lower()
        toks = phrase_str.split()
        tok_count = len(toks)
        role = p.get("role", "UNKNOWN")
        concept = p.get("concept", "NONE")
        target_cat = p.get("targetCategory", "UNKNOWN_OBJECT")
        is_pos_ob = p.get("isPositiveObligation", False)
        is_glob = p.get("isGlobalScope", False)
        processed_phrases.append({
            "phrase": phrase_str,
            "tokenCount": tok_count,
            "role": role,
            "concept": concept,
            "targetCategory": target_cat,
            "isPositiveObligation": is_pos_ob,
            "isGlobalScope": is_glob
        })

    processed_phrases.sort(key=lambda x: (-x["tokenCount"], -len(x["phrase"]), x["phrase"]))

    lines = []
    lines.append("// Auto-generated by tools/generate_parser_tables.py - DO NOT EDIT MANUALLY")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("#include <cstddef>")
    lines.append("")
    lines.append("namespace VoiceJournal::Parser {")
    lines.append("")

    # ConceptId
    lines.append("enum class ConceptId : uint8_t {")
    lines.append("    NONE = 0,")
    for i, c in enumerate(concept_names):
        lines.append(f"    {c} = {i + 1},")
    lines.append("};")
    lines.append("")

    lines.append("namespace ConceptMask {")
    lines.append("    constexpr uint32_t NONE = 0u;")
    for i, c in enumerate(concept_names):
        lines.append(f"    constexpr uint32_t {c} = (1u << {i});")
    lines.append("}")
    lines.append("")

    lines.append("inline const char* conceptToString(ConceptId id) {")
    lines.append("    switch (id) {")
    lines.append("        case ConceptId::NONE: return \"NONE\";")
    for c in concept_names:
        lines.append(f"        case ConceptId::{c}: return \"{c}\";")
    lines.append("        default: return \"UNKNOWN\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # SemanticRole
    lines.append("enum class SemanticRole : uint8_t {")
    for i, r in enumerate(semantic_roles):
        lines.append(f"    {r} = {i},")
    lines.append("};")
    lines.append("")

    lines.append("inline const char* semanticRoleToString(SemanticRole role) {")
    lines.append("    switch (role) {")
    for r in semantic_roles:
        lines.append(f"        case SemanticRole::{r}: return \"{r}\";")
    lines.append("        default: return \"UNKNOWN\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # TargetCategory
    lines.append("enum class TargetCategory : uint8_t {")
    for i, tc in enumerate(target_categories):
        lines.append(f"    {tc} = {i},")
    lines.append("};")
    lines.append("")

    lines.append("inline const char* targetCategoryToString(TargetCategory cat) {")
    lines.append("    switch (cat) {")
    for tc in target_categories:
        lines.append(f"        case TargetCategory::{tc}: return \"{tc}\";")
    lines.append("        default: return \"UNKNOWN\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Intents enum
    all_intents = [
        ("UNKNOWN", True),
        ("NO_ACTION", True),
        ("AMBIGUOUS", True),
        ("ADD_NOTE", True),
        ("READ_LAST_NOTE", True),
        ("COUNT_NOTES", True),
        ("ANALYZE_NOTES", True),
        ("REQUEST_CLEAR", True),
        ("CONFIRM_CLEAR", True),
        ("CANCEL_CLEAR", True),
        ("HELP", True),
        ("SEARCH_NOTES", False),
        ("ADD_TASK", False),
        ("RESOLVE_PROBLEM", False),
        ("LIST_TASKS", False),
        ("SEARCH_BY_PROJECT", False),
        ("SEARCH_BY_DATE", False),
        ("ANALYZE_PROJECT", False),
    ]

    lines.append("enum class IntentId : uint8_t {")
    for i, (name, _) in enumerate(all_intents):
        lines.append(f"    {name} = {i},")
    lines.append("};")
    lines.append("")

    lines.append("inline const char* intentToString(IntentId id) {")
    lines.append("    switch (id) {")
    for name, _ in all_intents:
        lines.append(f"        case IntentId::{name}: return \"{name}\";")
    lines.append("        default: return \"UNKNOWN\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("inline constexpr bool isIntentExecutable(IntentId id) {")
    lines.append("    switch (id) {")
    for name, exec_flag in all_intents:
        if exec_flag and name not in ("UNKNOWN", "NO_ACTION", "AMBIGUOUS"):
            lines.append(f"        case IntentId::{name}: return true;")
    lines.append("        default: return false;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("inline constexpr bool isIntentExperimental(IntentId id) {")
    lines.append("    switch (id) {")
    for name, exec_flag in all_intents:
        if not exec_flag:
            lines.append(f"        case IntentId::{name}: return true;")
    lines.append("        default: return false;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Entities
    lines.append("enum class EntityId : uint8_t {")
    for e in entity_enums:
        lines.append(f"    {e},")
    lines.append("};")
    lines.append("")

    lines.append("enum class EntityType : uint8_t {")
    for t in entity_type_enums:
        lines.append(f"    {t},")
    lines.append("};")
    lines.append("")

    lines.append("inline const char* entityToString(EntityId id) {")
    lines.append("    switch (id) {")
    lines.append("        case EntityId::ENT_NONE: return \"NONE\";")
    for e in entities_data:
        lines.append(f"        case EntityId::ENT_{e['id']}: return \"{e['canonical']}\";")
    lines.append("        default: return \"UNKNOWN\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Lexicon table
    lines.append("struct LexiconEntry {")
    lines.append("    const char* word;")
    lines.append("    uint32_t conceptMask;")
    lines.append("};")
    lines.append("")
    lines.append(f"constexpr size_t LEXICON_COUNT = {len(sorted_words)};")
    lines.append("inline constexpr LexiconEntry LEXICON_TABLE[LEXICON_COUNT] = {")
    for w in sorted_words:
        lines.append(f"    {{\"{w}\", {hex(lexicon[w])}u}},")
    lines.append("};")
    lines.append("")

    # Phrase table
    lines.append("struct PhraseEntry {")
    lines.append("    const char* phrase;")
    lines.append("    uint8_t tokenCount;")
    lines.append("    SemanticRole role;")
    lines.append("    ConceptId conceptId;")
    lines.append("    TargetCategory targetCategory;")
    lines.append("    bool isPositiveObligation;")
    lines.append("    bool isGlobalScope;")
    lines.append("};")
    lines.append("")
    lines.append(f"constexpr size_t PHRASE_COUNT = {len(processed_phrases)};")
    lines.append("inline constexpr PhraseEntry PHRASE_TABLE[PHRASE_COUNT] = {")
    for p in processed_phrases:
        cid = f"ConceptId::{p['concept']}" if p['concept'] in concept_names else "ConceptId::NONE"
        pos_ob = "true" if p["isPositiveObligation"] else "false"
        glob_sc = "true" if p["isGlobalScope"] else "false"
        lines.append(f"    {{\"{p['phrase']}\", {p['tokenCount']}, SemanticRole::{p['role']}, {cid}, TargetCategory::{p['targetCategory']}, {pos_ob}, {glob_sc}}},")
    lines.append("};")
    lines.append("")

    # Grammar Rules
    lines.append("struct GrammarRule {")
    lines.append("    const char* id;")
    lines.append("    IntentId intent;")
    lines.append("    uint8_t priority;")
    lines.append("    uint8_t baseScore;")
    lines.append("    bool executable;")
    lines.append("    uint32_t requiredConcepts;")
    lines.append("    uint32_t optionalConcepts;")
    lines.append("    uint32_t forbiddenConcepts;")
    lines.append("    uint16_t allowedTargetsMask;")
    lines.append("    uint16_t forbiddenTargetsMask;")
    lines.append("    ConceptId startsWithConcept;")
    lines.append("    bool exactMatchRequired;")
    lines.append("    bool requireActionPayload;")
    lines.append("    bool requireGlobalScope;")
    lines.append("    bool rejectNegatedCommand;")
    lines.append("    bool rejectNegatedObligation;")
    lines.append("    bool requiresEntity;")
    lines.append("    bool forbiddenEntities;")
    lines.append("    bool requiresNegation;")
    lines.append("    bool rejectNegation;")
    lines.append("};")
    lines.append("")

    def make_concept_mask(concept_list):
        mask = 0
        for c in concept_list:
            if c in concept_to_bit:
                mask |= (1 << concept_to_bit[c])
        return hex(mask) + "u"

    def make_target_mask(target_list):
        mask = 0
        for t in target_list:
            if t in target_categories:
                mask |= (1 << target_categories.index(t))
        return hex(mask) + "u"

    lines.append(f"constexpr size_t GRAMMAR_RULE_COUNT = {len(grammar_data)};")
    lines.append("inline constexpr GrammarRule GRAMMAR_RULES[GRAMMAR_RULE_COUNT] = {")
    for r in grammar_data:
        req_c = make_concept_mask(r.get("requiredConcepts", []))
        opt_c = make_concept_mask(r.get("optionalConcepts", []))
        forb_c = make_concept_mask(r.get("forbiddenConcepts", []))
        allow_t = make_target_mask(r.get("allowedTargets", []))
        forb_t = make_target_mask(r.get("forbiddenTargets", []))

        start_c = r.get("startsWithConcept", "NONE")
        start_c_str = f"ConceptId::{start_c}" if start_c in concept_names else "ConceptId::NONE"

        exact_match = "true" if r.get("exactMatchRequired", False) else "false"
        req_payload = "true" if r.get("requireActionPayload", False) else "false"
        req_global = "true" if r.get("requireGlobalScope", False) else "false"
        rej_neg_cmd = "true" if r.get("rejectNegatedCommand", False) else "false"
        rej_neg_ob = "true" if r.get("rejectNegatedObligation", False) else "false"
        req_ent = "true" if r.get("requiresEntity", False) else "false"
        forb_ent = "true" if r.get("forbiddenEntities", False) else "false"
        req_neg = "true" if r.get("requiresNegation", False) else "false"
        rej_neg = "true" if r.get("rejectNegation", False) else "false"
        exec_str = "true" if r.get("executable", False) else "false"

        lines.append("    {")
        lines.append(f"        \"{r['id']}\", IntentId::{r['intent']}, {r.get('priority', 50)}, {r.get('baseScore', 90)}, {exec_str},")
        lines.append(f"        {req_c}, {opt_c}, {forb_c},")
        lines.append(f"        {allow_t}, {forb_t},")
        lines.append(f"        {start_c_str}, {exact_match}, {req_payload}, {req_global},")
        lines.append(f"        {rej_neg_cmd}, {rej_neg_ob}, {req_ent}, {forb_ent}, {req_neg}, {rej_neg}")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    # Entity alias table
    lines.append("struct EntityAliasEntry {")
    lines.append("    const char* alias;")
    lines.append("    EntityId entityId;")
    lines.append("    EntityType type;")
    lines.append("};")
    lines.append("")
    lines.append(f"constexpr size_t ENTITY_ALIAS_COUNT = {len(entity_aliases)};")
    lines.append("inline constexpr EntityAliasEntry ENTITY_ALIAS_TABLE[ENTITY_ALIAS_COUNT] = {")
    id_to_type = {f"ENT_{e['id']}": e["type"] for e in entities_data}
    for alias, eid in entity_aliases:
        etype = id_to_type[eid]
        lines.append(f"    {{\"{alias}\", EntityId::{eid}, EntityType::{etype}}},")
    lines.append("};")
    lines.append("")

    # Confirm phrases
    lines.append(f"constexpr size_t CONFIRM_PHRASE_COUNT = {len(confirm_phrases)};")
    lines.append("inline constexpr const char* CONFIRM_PHRASES[CONFIRM_PHRASE_COUNT] = {")
    for p in confirm_phrases:
        lines.append(f"    \"{p}\",")
    lines.append("};")
    lines.append("")

    lines.append("} // namespace VoiceJournal::Parser\n")

    content = "\n".join(lines)
    with open(output_header, "w", encoding="utf-8") as f:
        f.write(content)
    with open(output_header_src, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Generated {output_header} and {output_header_src} successfully.")
    print(f"Lexicon entries: {len(sorted_words)}")
    print(f"Phrase entries: {len(processed_phrases)}")
    print(f"Grammar rules: {len(grammar_data)}")
    print(f"Entity aliases: {len(entity_aliases)}")
    print(f"Confirm phrases: {len(confirm_phrases)}")

if __name__ == "__main__":
    main()
